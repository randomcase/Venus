#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   guild.mjs — builds guild.html: the board that settles the harvest guarantee,
   and the quest board, which is authored rather than derived.

   TWO DEMONSTRATIONS AND A JOB LIST.

   1 THE LADDER. One newcomer, a hundred units of output, five ranks above
     them. Without the guarantee each rank takes a cut of what passes up and
     the newcomer keeps 41 of 100 — 59 of it reaching people who contributed
     nothing to it, by rank alone. With the guarantee they keep 100 and the
     ranks above earn from their own. Same output, same ladder, one term.

   2 THE RENAME DEFEATS IT ANYWAY, which is the entry's stated limit made
     watchable. Leave the guarantee ON and reclassify the contribution as
     pooled, and the guaranteed stream becomes a share of a pool rather than
     a claim on your own output — 2 of 100 across fifty members. The transfer
     was enforced perfectly. The definition ate it upstream, where the
     contract does not reach.

   3 THE QUESTS ARE AUTHORED, NOT DERIVED. An earlier draft generated one job
     per knowledge-base entry, which meant the board grew every time somebody
     wrote an entry — a loop, shipped as a feature. Quests now live in
     templates-quest/ with four required fields (giver, object, done,
     produces) and are refused by quests.mjs if `produces` names a quest, if
     `done` depends on another one, or if the requires graph cycles or runs
     deeper than three.

     None of them is worth more than another. There are no points, no tiers
     and no order: doing one is +1 and which one you did is not comparable.
     A quest board with a difficulty rating is a ladder, and this whole page
     is about what a ladder does.

       node guild.mjs
   ═══════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const rich = (s) => esc(s)
  .replace(/`([^`]+)`/g, '<code>$1</code>')
  .replace(/\b([A-Z][A-Z ’']{3,}[A-Z])\b/g, '<em>$1</em>');

const kb = JSON.parse(readFileSync('kb.json', 'utf8'));

/* THE QUESTS COME FROM templates-quest/, NOT FROM kb.json, AND THAT IS A FIX.
   The first draft of this file generated one job per knowledge-base entry and
   said so as though it were a feature: "write a new entry and a new job appears
   without anybody maintaining a second list." That is a board that grows by
   being read — a loop with a story on it — and it would have filled up with
   work about the board. Quests are authored, validated by quests.mjs against
   three anti-recursion rules, and compiled separately. */
const QDIR = 'templates-quest';
const quests = readdirSync(QDIR).filter((f) => f.endsWith('.json')).sort()
  .map((f) => JSON.parse(readFileSync(join(QDIR, f), 'utf8')));

/* the ladder, computed rather than typed */
