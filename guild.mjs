let left = START; const rows = [];
for (let r = 2; r <= RANKS; r++) {
  const take = left * CUT;
  rows.push({ r, take, left: left - take });
  left -= take;
}
const kept = left, taken = START - kept;
const POOL = 50, pooled = START / POOL;

const CLS = { concept: 'survey', mechanism: 'field work', figure: 'interview',
              number: 'measurement' };

const SKY = readFileSync('.sky-block.txt', 'utf8').replace('#060a08', '#0b0910');

